-- js/rediseno-ia.js intentaba guardar (best-effort) cada lead del chat de
-- rediseno con IA en una tabla "leads" que en realidad solo tiene las
-- columnas (msg_key, created_at) del contador de clics de WhatsApp. El
-- insert fallaba siempre (columnas inexistentes), asi que ningun lead del
-- chat de rediseno se estaba guardando. Se crea una tabla dedicada.

create table public.redesign_leads (
  id bigint generated by default as identity primary key,
  photo_url text not null,
  style text not null,
  status text not null default 'pendiente_rediseno',
  source text not null default 'acero-press-chat',
  created_at timestamptz not null default now()
);

alter table public.redesign_leads enable row level security;

-- El widget de chat corre sin autenticacion: cualquier visitante debe poder
-- crear su propio lead al subir una foto.
create policy "cualquiera puede crear un lead de rediseno"
  on public.redesign_leads
  for insert
  with check (true);

-- Solo el equipo (admin_users) puede leer los leads generados.
create policy "solo admin lee leads de rediseno"
  on public.redesign_leads
  for select
  using (is_admin());
